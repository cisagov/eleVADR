"""Rebuild deterministic regression fixtures that are not stored in git.

Datasets 15, 16, 17 and 19 are generated by stdlib-only builders, and
``synthetic_pcap_corpus`` pins their SHA-256, so a rebuilt file is verified.
Datasets 01-03 are frozen captures and cannot be rebuilt: this script only
reports them. It never overwrites an existing file.

Usage: python -m backend.regression.ensure_fixtures
"""
from __future__ import annotations

import argparse

from backend.regression.frozen_policy import ENV_VAR
from backend.regression.synthetic_pcap_corpus import CORPUS, FIXTURES

DATASET05 = FIXTURES / "05_parser_edge_cases"


def ensure_fixtures() -> list[str]:
    """Return human-readable problems that cannot be fixed automatically."""
    problems: list[str] = []
    for entry in CORPUS:
        pcap = FIXTURES / entry.pcap
        if pcap.is_file():
            continue
        if entry.builder is None:
            problems.append(
                f"Dataset {entry.dataset:02d}: frozen capture {entry.pcap} is missing and cannot be rebuilt. "
                f"Restore it into {FIXTURES} (expected SHA-256 {entry.sha256})."
            )
            continue
        print(f"Rebuilding missing fixture {entry.pcap} ...")
        entry.builder(pcap)
    for name in ("conn.log", "dns.log"):
        if not (DATASET05 / name).is_file():
            problems.append(f"Dataset 05: {name} is missing from {DATASET05}; restore it from the original fixtures.")
    return problems


def frozen_status() -> int:
    """Print a waiver notice and return 1 if any frozen capture is missing, else 0."""
    missing = [e for e in CORPUS if e.builder is None and not (FIXTURES / e.pcap).is_file()]
    if not missing:
        return 0
    print("*" * 60)
    print(f"WAIVER ACTIVE ({ENV_VAR}=1): {len(missing)} frozen capture(s) missing:")
    for entry in missing:
        print(f"  - Dataset {entry.dataset:02d}: {entry.pcap}")
    print("Live Zeek validation of these datasets did NOT run; this is not a full pass.")
    print("*" * 60)
    return 1


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--frozen-status", action="store_true", help="report missing frozen captures; exit 1 if any")
    if parser.parse_args().frozen_status:
        return frozen_status()
    problems = ensure_fixtures()
    if problems:
        print("WARNING: some regression fixtures cannot be generated:")
        for item in problems:
            print(f"  - {item}")
    else:
        print("Regression fixtures present.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
